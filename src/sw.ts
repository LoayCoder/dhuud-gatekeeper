// Store notification in history by sending to clients
function storeNotificationInHistory(title: string, body: string, type: string) {
  self.clients.matchAll().then(clients => {
    clients.forEach(client => {
      client.postMessage({
        type: 'STORE_NOTIFICATION',
        notification: { title, body, type }
      });
    });
  });
}

// Show notification for sync results
async function showSyncNotification(result: { success: number; failed: number }) {
  // Check if we have notification permission
  if (self.Notification?.permission !== 'granted') {
    return;
  }

  const { success, failed } = result;
  
  // Don't show notification if nothing happened
  if (success === 0 && failed === 0) {
    return;
  }

  const title = failed > 0 ? 'Sync Partially Failed' : 'Sync Complete';
  const body = failed > 0
    ? `${success} change(s) synced, ${failed} failed`
    : `${success} change(s) synced successfully`;
  const icon = 'https://xdlowvfzhvjzbtgvurzj.supabase.co/storage/v1/object/public/branding/9290e913-c735-405c-91c6-141e966011ae/favicon/1764707368310.png';
  const tag = 'sync-notification';
  const notificationType = failed > 0 ? 'error' : 'sync';

  try {
    await self.registration.showNotification(title, {
      body,
      icon,
      tag,
      badge: 'https://xdlowvfzhvjzbtgvurzj.supabase.co/storage/v1/object/public/branding/9290e913-c735-405c-91c6-141e966011ae/favicon/1764707368310.png',
      vibrate: [100, 50, 100],
      data: { success, failed },
      actions: failed > 0 ? [
        { action: 'retry', title: 'Retry' },
        { action: 'dismiss', title: 'Dismiss' }
      ] : []
    } as ExtendedNotificationOptions);
    
    // Store in notification history
    storeNotificationInHistory(title, body, notificationType);
  } catch (error) {
    console.error('Failed to show notification:', error);
  }
}

// Handle notification click with security-specific actions
self.addEventListener('notificationclick', (event: any) => {
  event.notification.close();

  const notificationData = event.notification.data || {};
  const action = event.action;

  // Handle retry action for sync
  if (action === 'retry') {
    event.waitUntil(processMutationQueue());
    return;
  }

  // Handle update action
  if (action === 'update' || notificationData.type === 'update') {
    event.waitUntil(
      (async () => {
        // @ts-ignore
        if (self.registration.waiting) {
          // @ts-ignore
          self.registration.waiting.postMessage({ type: 'SKIP_WAITING' });
        }
        const cacheNames = await caches.keys();
        await Promise.all(
          cacheNames
            .filter(name => name.startsWith('dhuud-'))
            .map(name => {
              console.log('[SW] Clearing cache for update:', name);
              return caches.delete(name);
            })
        );
        const clients = await self.clients.matchAll({ type: 'window' });
        for (const client of clients) {
          await client.navigate(client.url);
        }
      })()
    );
    return;
  }

  // Handle emergency alert actions
  if (notificationData.type === 'emergency_alert') {
    const alertId = notificationData.alert_id;
    
    if (action === 'acknowledge') {
      // Acknowledge the alert via API call
      event.waitUntil(
        (async () => {
          try {
            // Try to acknowledge via edge function
            const response = await fetch(
              `https://xdlowvfzhvjzbtgvurzj.supabase.co/functions/v1/acknowledge-emergency-alert`,
              {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ alert_id: alertId })
              }
            );
            console.log('[SW] Emergency alert acknowledged:', response.ok);
          } catch (err) {
            console.error('[SW] Failed to acknowledge alert:', err);
          }
          
          // Navigate to alert details
          const clients = await self.clients.matchAll({ type: 'window' });
          const targetUrl = notificationData.action_url || `/security/emergency-alerts?id=${alertId}`;
          if (clients.length > 0) {
            return clients[0].navigate(targetUrl).then((client: any) => client.focus());
          }
          return self.clients.openWindow(targetUrl);
        })()
      );
      return;
    }
    
    if (action === 'view' || !action) {
      // Navigate to emergency alert details
      const targetUrl = notificationData.action_url || `/security/emergency-alerts?id=${alertId}`;
      event.waitUntil(
        self.clients.matchAll({ type: 'window' }).then((clients) => {
          if (clients.length > 0) {
            return clients[0].navigate(targetUrl).then((client: any) => client.focus());
          }
          return self.clients.openWindow(targetUrl);
        })
      );
      return;
    }
    
    if (action === 'map' && notificationData.gps_lat && notificationData.gps_lng) {
      // Open Google Maps with location
      const mapsUrl = `https://maps.google.com/?q=${notificationData.gps_lat},${notificationData.gps_lng}`;
      event.waitUntil(self.clients.openWindow(mapsUrl));
      return;
    }
  }

  // Handle SLA escalation
  if (notificationData.type === 'sla_escalation') {
    event.waitUntil(
      self.clients.matchAll({ type: 'window' }).then((clients) => {
        const url = '/admin/sla-dashboard';
        if (clients.length > 0) {
          return clients[0].navigate(url).then((client: any) => client.focus());
        }
        return self.clients.openWindow(url);
      })
    );
    return;
  }

  // Default: Open or focus the app with action_url if provided
  const targetUrl = notificationData.action_url || '/';
  event.waitUntil(
    self.clients.matchAll({ type: 'window' }).then((clients) => {
      if (clients.length > 0) {
        return clients[0].navigate(targetUrl).then((client: any) => client.focus());
      }
      return self.clients.openWindow(targetUrl);
    })
  );
});

