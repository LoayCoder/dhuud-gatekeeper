// Process queued mutations
async function processMutationQueue() {
  const result = { success: 0, failed: 0 };
  
  try {
    const clients = await self.clients.matchAll();
    if (clients.length === 0) return result;
    
    const client = clients[0];
    
    return new Promise<{ success: number; failed: number }>((resolve) => {
      const messageChannel = new MessageChannel();
      
      messageChannel.port1.onmessage = async (event) => {
        const mutations = event.data.mutations || [];
        
        for (const mutation of mutations) {
          try {
            const response = await executeMutation(mutation);

            if (response.ok) {
              result.success++;
              client.postMessage({ 
                type: 'MUTATION_SUCCESS', 
                id: mutation.id 
              });
            } else if (response.status >= 400 && response.status < 500) {
              result.failed++;
              client.postMessage({
                type: 'MUTATION_FAILED_PERMANENT',
                id: mutation.id,
                error: `Permanent failure: ${response.status} ${response.statusText}`
              });
            } else if (response.status >= 500) {
              result.failed++;
              client.postMessage({
                type: 'MUTATION_FAILED_RETRYABLE',
                id: mutation.id,
                error: `Retryable failure: ${response.status} ${response.statusText}`
              });
            } else {
              result.failed++;
              client.postMessage({
                type: 'MUTATION_FAILED_RETRYABLE',
                id: mutation.id,
                error: `Unknown failure: ${response.status} ${response.statusText}`
              });
            }
          } catch (error: any) {
            result.failed++;
            client.postMessage({
              type: 'MUTATION_FAILED_RETRYABLE',
              id: mutation.id,
              error: `Network/System error: ${error.message}`
            });
          }
        }
        
        resolve(result);
      };
      
      client.postMessage(
        { type: 'GET_MUTATIONS' },
        [messageChannel.port2]
      );
      
      setTimeout(() => resolve(result), 30000);
    });
  } catch (error) {
    console.error('Background sync failed:', error);
    return result;
  }
}

// Execute a single mutation
async function executeMutation(mutation: any) {
  if (!mutation.endpoint) {
    return {
      ok: false,
      status: 400,
      statusText: 'Missing endpoint'
    } as Response;
  }
  
  const response = await fetch(mutation.endpoint, {
    method: mutation.method || 'POST',
    headers: {
      'Content-Type': 'application/json',
      ...mutation.headers,
    },
    body: mutation.body ? JSON.stringify(mutation.body) : undefined,
  });
  
  if (response.ok && mutation.mutationKey) {
    const key = mutation.mutationKey.toLowerCase();
    if (key.includes('incident') || key.includes('observation')) {
      await triggerIncidentNotification(mutation, response.clone());
    }
  }
  
  return response;
}

async function triggerIncidentNotification(mutation: any, response: Response) {
  try {
    const data = await response.json();
    const incidentId = data?.id || data?.data?.id;
    
    if (!incidentId) {
      console.log('[SW] No incident ID found in response, skipping notification');
      return;
    }
    
    // @ts-ignore
    const supabaseUrl = mutation.endpoint?.split('/rest/')[0] || self.SUPABASE_URL || 'https://xdlowvfzhvjzbtgvurzj.supabase.co';
    
    const notifyResponse = await fetch(`${supabaseUrl}/functions/v1/dispatch-incident-notification`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': mutation.headers?.Authorization || mutation.headers?.authorization || '',
      },
      body: JSON.stringify({
        incident_id: incidentId,
        event_type: 'incident_created',
        source: 'offline_sync'
      }),
    });
    
    if (notifyResponse.ok) {
      console.log('[SW] Notification dispatched for synced incident:', incidentId);
    }
  } catch (error) {
    console.error('[SW] Failed to trigger incident notification:', error);
  }
}
